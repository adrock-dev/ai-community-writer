/** 장면에 붙이는 분위기. 실내·실외 어디에나 맞는 색감·빛만 둔다. */
const MOODS = [
  "밝고 산뜻한 오전 햇살",
  "따뜻한 늦은 오후 햇빛",
  "흐린 날의 차분하고 부드러운 빛",
  "선명하고 맑은 색감",
  "은은하고 따뜻한 색감",
];

/** 장면 설명(삽화 subject)이 어느 장면에서 나왔는지 판정할 때 쓰는 구분자 */
const MOOD_SEP = ". 분위기: ";

export function scenePool(articleType: string): string[] {
  return SCENES[articleType] ?? SCENES.guide!;
}

/**
 * 글에 쓸 장면을 고른다. recent 는 같은 유형의 최근 글에 쓴 삽화 장면(최신 순)이다.
 * 쓴 적 없는 장면 → 오래전에 쓴 장면 순으로 고르고, 같은 순위는 무작위로 섞는다.
 */
export function pickScenes(
  articleType: string,
  count: number,
  recent: string[],
  random: () => number,
): string[] {
  const lastUsed = (scene: string) => {
    const i = recent.findIndex((s) => s === scene || s.startsWith(`${scene}${MOOD_SEP}`));
    return i < 0 ? Number.POSITIVE_INFINITY : i;
  };
  const mood = MOODS[Math.floor(random() * MOODS.length)] ?? MOODS[0]!;
  return scenePool(articleType)
    .map((scene) => ({ scene, age: lastUsed(scene), order: random() }))
    .sort((a, b) => (a.age === b.age ? a.order - b.order : b.age - a.age))
    .slice(0, Math.max(0, count))
    .map(({ scene }) => `${scene}${MOOD_SEP}${mood}`);
}
